"""The native API surface used at the Krita boundary."""

from typing import List, Optional, Protocol, Sequence

from PyQt5.QtCore import QByteArray, QRectF, QUuid
from PyQt5.QtGui import QImage, QTransform


class Shape(Protocol):
    def name(self) -> str: ...
    def setName(self, name: str) -> None: ...
    def type(self) -> str: ...
    def children(self) -> List["Shape"]: ...
    def isSelected(self) -> bool: ...
    def select(self) -> None: ...
    def deselect(self) -> None: ...
    def zIndex(self) -> int: ...
    def setZIndex(self, index: int) -> None: ...
    def setVisible(self, visible: bool) -> None: ...
    def transformation(self) -> QTransform: ...
    def absoluteTransformation(self) -> QTransform: ...
    def setTransformation(self, transform: QTransform) -> None: ...
    def boundingBox(self) -> QRectF: ...
    def updateAbsolute(self, bounds: QRectF) -> None: ...
    def update(self) -> None: ...
    def remove(self) -> bool: ...


class Node(Protocol):
    def uniqueId(self) -> QUuid: ...
    def name(self) -> str: ...
    def type(self) -> str: ...
    def locked(self) -> bool: ...
    def parentNode(self) -> Optional["Node"]: ...
    def childNodes(self) -> List["Node"]: ...
    def addChildNode(self, child: "Node", above: Optional["Node"]) -> bool: ...
    def setVisible(self, visible: bool) -> None: ...
    def remove(self) -> bool: ...
    def shapes(self) -> List[Shape]: ...
    def toSvg(self) -> str: ...
    def addShapesFromSvg(self, svg: str) -> List[Shape]: ...
    def createGroupShape(self, name: str, shapes: Sequence[Shape]) -> Optional[Shape]: ...


class Document(Protocol):
    def activeNode(self) -> Optional[Node]: ...
    def rootNode(self) -> Node: ...
    def createVectorLayer(self, name: str) -> Optional[Node]: ...
    def setActiveNode(self, node: Node) -> None: ...
    def nodeByUniqueID(self, identifier: QUuid) -> Optional[Node]: ...
    def annotation(self, key: str) -> QByteArray: ...
    def setAnnotation(self, key: str, description: str, value: QByteArray) -> None: ...
    def waitForDone(self) -> None: ...
    def refreshProjection(self) -> None: ...
    def xRes(self) -> float: ...
    def yRes(self) -> float: ...
    def width(self) -> int: ...
    def height(self) -> int: ...
    def clone(self) -> Optional["Document"]: ...
    def thumbnail(self, width: int, height: int) -> QImage: ...
    def close(self) -> bool: ...


class Host(Protocol):
    def activeDocument(self) -> Optional[Document]: ...
    def addDockWidgetFactory(self, factory: object) -> None: ...
