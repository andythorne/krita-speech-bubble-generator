"""Structural service boundaries for editor orchestration."""

from typing import Callable, Optional, Protocol, Tuple, TypeVar

from PyQt5.QtCore import QPointF, QRectF
from PyQt5.QtGui import QImage, QTransform

from ..bubbles.settings import BubbleSettings
from .state import BubbleTarget, CanvasContext, LoadedBubble, Selection


class GatewayError(ValueError):
    """An expected host failure that should be shown to the user."""


class TargetMissing(GatewayError):
    """The target can no longer be resolved without guessing."""


Slot = TypeVar("Slot", contravariant=True)


class Signal(Protocol[Slot]):
    def connect(self, slot: Slot) -> object: ...


class RenderedBubble(Protocol):
    @property
    def svg(self) -> str: ...
    @property
    def view_box(self) -> QRectF: ...
    @property
    def tip(self) -> Optional[QPointF]: ...


class PreviewContext(Protocol):
    @property
    def image(self) -> QImage: ...
    @property
    def rect(self) -> QRectF: ...
    @property
    def transform(self) -> QTransform: ...


class EditorView(Protocol):
    @property
    def edited(self) -> Signal[Callable[[BubbleSettings, Tuple[str, ...]], None]]: ...
    @property
    def tail_moved(self) -> Signal[Callable[[QPointF], None]]: ...
    @property
    def page_requested(self) -> Signal[Callable[[bool], None]]: ...
    @property
    def new_requested(self) -> Signal[Callable[[], None]]: ...
    @property
    def background_toggled(self) -> Signal[Callable[[bool], None]]: ...
    @property
    def refresh_requested(self) -> Signal[Callable[[], None]]: ...

    def initial_settings(self) -> BubbleSettings: ...
    def load_settings(self, settings: BubbleSettings) -> BubbleSettings: ...
    def reflect_settings(self, settings: BubbleSettings) -> BubbleSettings: ...
    def show_render(self, rendered: RenderedBubble) -> None: ...
    def show_context(self, context: Optional[PreviewContext]) -> None: ...
    def show_mode(self, editing: bool, label: str) -> None: ...
    def show_background(self, enabled: bool, available: bool) -> None: ...
    def is_dragging(self) -> bool: ...
    def warn(self, message: str) -> None: ...


class BubbleRendering(Protocol):
    def render(self, settings: BubbleSettings, preview: bool = False) -> RenderedBubble: ...
    def move_tail(self, settings: BubbleSettings, point: QPointF) -> BubbleSettings: ...


class BubbleGateway(Protocol):
    def active_document(self) -> object: ...
    def observe(self) -> Selection: ...
    def load_selected(self, shape_name: Optional[str] = None) -> LoadedBubble: ...
    def deselect(self) -> Selection: ...
    def create(self, settings: BubbleSettings, svg: str, new_layer: bool) -> LoadedBubble: ...
    def update(self, target: BubbleTarget, settings: BubbleSettings, svg: str) -> BubbleTarget: ...
    def placement(self, target: BubbleTarget) -> QTransform: ...
    def snapshot(self, target: BubbleTarget) -> CanvasContext: ...


SeedSupplier = Callable[[int, int], int]
